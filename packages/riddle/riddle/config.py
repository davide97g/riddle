# --- reading .env -------------------------------------------------------


def read_dotenv(path: Path) -> dict[str, str]:
    """A dotenv reader in twenty lines, with no interpolation.

    `set -a; source .env` would expand $VAR. Nothing in this project's .env
    uses that, and silently interpolating half a password is worse than not
    supporting it at all.
    """
    if not path.is_file():
        return {}
    found: dict[str, str] = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export "):].lstrip()
        key, sep, value = line.partition("=")
        if not sep:
            continue
        key, value = key.strip(), value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        found[key] = value
    return found


def _coerce(setting: Setting, raw: str):
    if setting.kind is bool:
        return raw.strip().lower() in ("1", "true", "yes", "on")
    if setting.kind is Path:
        base = {"root": paths.ROOT, "var": paths.VAR, "models": paths.MODELS}
        return paths.under_root(raw, base[setting.base])
    return setting.kind(raw)


_CONFIG: Config | None = None


def load(env_file: Path | None = None, *, use_dotenv: bool = True) -> Config:
    """Build the configuration once, from .env and the environment."""
    global _CONFIG
    path = env_file or (paths.ROOT / ".env")
    dotenv = read_dotenv(path) if use_dotenv else {}

    values: dict[str, object] = {}
    sources: dict[str, str] = {}
    derived: list[Setting] = []
    for setting in SETTINGS:
        if setting.manual:
            continue
        if setting.name in os.environ:
            raw, where = os.environ[setting.name], "env"
        elif setting.name in dotenv:
            raw, where = dotenv[setting.name], ".env"
        elif setting.derive is not None:
            derived.append(setting)
            continue
        else:
            raw, where = None, "default"
        if raw is None:
            default = setting.default
            if setting.kind is Path and isinstance(default, str):
                default = _coerce(setting, default)
            values[setting.attr] = default
        else:
            values[setting.attr] = _coerce(setting, raw)
        sources[setting.name] = where

    # A derived setting is a function of the others, so the others are built
    # first and it reads them off a throwaway copy.
    partial = Config(**values, **{s.attr: "" for s in derived}, sources=sources)
    for setting in derived:
        values[setting.attr] = setting.derive(partial)
        sources[setting.name] = "derived"
    _CONFIG = Config(**values, sources=sources)
    return _CONFIG


def get() -> Config:
    """The loaded configuration. The CLI loads it before anything else runs."""
    if _CONFIG is None:
        return load()
    return _CONFIG


# --- printing itself ----------------------------------------------------


def as_example() -> str:
    """`.env.example`, generated.

    Every value is commented out at its code default. That is the whole
    trick: a template that sets nothing cannot drift from the code.
    """
    out = [
        "# Copy to .env and fill in what you want to change. .env is",
        "# gitignored and must never be committed: it holds the tablet's",
        "# root password.",
        "#",
        "# Generated by `riddle config --example`. Every line below is the",
        "# code's own default, commented out -- uncomment to override.",
    ]
    for section in SECTIONS:
        out.append("")
        out.append(f"# --- {SECTION_TITLES[section]} ---")
        for setting in SETTINGS:
            if setting.section != section:
                continue
            for line in _wrap(setting.help):
                out.append(f"# {line}")
            shown = setting.default
            if setting.derive is not None:
                shown = "<derived from RIDDLE_WEB_HOST and RIDDLE_WEB_PORT>"
            elif isinstance(shown, bool):
                shown = "1" if shown else ""
            out.append(f"# {setting.name}={shown if shown is not None else ''}")
            out.append("")
        out.pop()
    return "\n".join(out) + "\n"


def _wrap(text: str, width: int = 72) -> list[str]:
    words, lines, line = text.split(), [], ""
    for word in words:
        if line and len(line) + 1 + len(word) > width:
            lines.append(line)
            line = word
        else:
            line = f"{line} {word}".strip()
    if line:
        lines.append(line)
    return lines


def check(env_file: Path | None = None) -> list[str]:
    """Everything wrong with the configuration, as sentences."""
    path = env_file or (paths.ROOT / ".env")
    problems: list[str] = []
    dotenv = read_dotenv(path)
    for key in dotenv:
        if key not in BY_NAME:
            problems.append(f"{path.name} sets {key}, which nothing reads")
    for name, raw in dotenv.items():
        setting = BY_NAME.get(name)
        if setting is None or setting.kind in (str, Path, bool):
            continue
        try:
            setting.kind(raw)
        except ValueError:
            problems.append(f"{name}={raw!r} is not a {setting.kind.__name__}")
    example = paths.ROOT / ".env.example"
    if example.is_file() and example.read_text() != as_example():
        problems.append(".env.example is stale: regenerate with `riddle config --example`")
    if path.is_file() and (path.stat().st_mode & 0o077):
        problems.append(f"{path.name} is readable by others; chmod 600 it")
    return problems
