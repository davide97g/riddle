"""Every knob this project has, declared once.

There were thirty-two scattered `os.environ.get` calls before this, and three
of them disagreed with each other about the default: the loop wrote short
replies in one hand while the tool that previews the hand drew another, and
the notebook the consent gate named was not the notebook the loop announced.
A default that appears twice will eventually appear twice differently.

Two other things follow from putting them in one place. `.env` is read here,
in Python, so a tool picks up the same configuration the launcher does --
before, only the shell scripts sourced it and running a tool directly got
bare defaults. And `.env.example` is *generated* from these declarations
rather than maintained by hand, which is why every line in it is commented
out: a template cannot disagree with a default it does not set.

Precedence is the usual one: a variable already in the environment beats
`.env`, so `RM2_SSH_HOST=rm2 riddle device build` works for a one-off. That
inverts what `set -a; source .env` used to do, so `riddle config` prints
where each value came from.
"""

